"use strict";
// Brand-specific source checks only; build/browser testing must be run separately.
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const r = path.resolve(__dirname, '..');
const read = p => fs.readFileSync(path.join(r,p),'utf8');
const exists = p => fs.existsSync(path.join(r,p));
for (const file of ['public/branding/sodepi-logo.png','public/branding/sodepi-symbol.png','src/app/icon.png','public/branding/favicon.ico']) assert.ok(exists(file), file);
const css=read('src/app/globals.css');
assert.ok(css.includes('--primary: #bd202a;'));
assert.ok(css.includes('--sidebar: #1b232c;'));
assert.ok(css.includes('--destructive: #b42318;'));
assert.ok(!css.includes('--primary: oklch(0.205 0 0)'));
const login=read('src/app/login/page.tsx');
assert.ok(login.includes('<SodepiLogo') && login.includes('<SodepiSymbol'));
assert.ok(login.includes('fetch("/api/auth/login"'));
assert.ok(login.includes('ERP SODEPI'));
const app=read('src/components/erp/erp-app.tsx');
assert.ok(app.includes('<SodepiSymbol'));
assert.ok(app.includes('fetch("/api/auth/logout"'));
assert.ok(read('src/components/erp/nav-sidebar.tsx').includes('<SodepiSymbol'));
assert.ok(read('src/components/erp/top-navigation.tsx').includes('bg-[#fff0f1]'));
assert.ok(read('src/components/ui/button.tsx').includes('bg-primary text-primary-foreground'));
assert.ok(read('src/components/ui/checkbox.tsx').includes('accent-primary'));
assert.ok(read('src/app/layout.tsx').includes('/branding/favicon.ico'));
assert.ok(!read('src/app/login/login.module.css').includes('#07865c'));
assert.ok(read('src/proxy.ts').includes('branding/'), 'Public logo assets must load on the login screen without a session');
console.log('PASS P5 : logo SODEPI, charte rouge/anthracite, points d’accueil, authentication inchangée.');
