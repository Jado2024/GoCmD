"use strict";
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const ts = require('typescript');
const root = path.resolve(__dirname,'..');
const code = fs.readFileSync(path.join(root,'src/components/erp/materials-view.tsx'),'utf8');
const source = ts.createSourceFile('materials-view.tsx',code,ts.ScriptTarget.Latest,true,ts.ScriptKind.TSX);
assert.equal(source.parseDiagnostics.length,0,'TSX : absence d’erreurs de syntaxe');
const tableStart = code.indexOf('<Table className={cn("table-fixed",canBuy?');
assert.notEqual(tableStart,-1,'Tableau responsive : 8 colonnes pour l acheteur, 4 sinon');
const tableEnd=code.indexOf('</Table>',tableStart);
const region=code.slice(tableStart,tableEnd);
const headers=Array.from(region.matchAll(/<TableHead\b[^>]*>([^<]+)<\/TableHead>/g),m=>m[1]);
assert.deepEqual(headers,['Code article','Désignation','Stock / état','DA à valider','Validées sans BC','BC brouillons','Reste à recevoir','Actions'],'huit colonnes acheteur');
assert.match(region,/colSpan=\{canBuy\?8:4\}/,'Etat vide par permission');
assert.match(region,/\{canBuy&&\(\["pendingQty","approvedQty","draftQty","orderedRemainingQty"\]/,'Colonnes des DA reservees a l acheteur');
assert.match(code,/overflow-x-auto scrollbar-thin/,'Scroll horizontal adapte');
assert.doesNotMatch(region,/TableHead[^\n]*>Coût CUMP/,'coûts toujours exclus du tableau');
assert.match(region,/\{m\.ref\}/,'référence article affichée');
assert.match(region,/\{m\.name\}/,'désignation affichée');
assert.match(region,/\[overflow-wrap:anywhere\]/,'références et désignations longues non tronquées');
assert.match(region,/fmtNum\(m\.stockQty\)/,'stock affiché');
assert.match(region,/fmtNum\(m\.minStock\)/,'seuil stock visible');
assert.match(region,/MaterialLevelBadge material=\{m\}/,'état du stock');
assert.match(code,/setInspecting\(m\)/,'ouverture fiche depuis désignation');
assert.match(code,/navigator\.clipboard\.writeText\(m\.ref\)/,'copie du code');
assert.match(code,/const canEdit=canCreate/,'droits d’édition conservés');
assert.match(code,/const canBuy=hasRole\(session\.data,"buyer"\)/,'droits DA conservés');
assert.match(code,/\{canEdit && <Button/, 'édition réservée au rôle autorisé');
assert.match(code,/\{canBuy && <Button/, 'DA réservée au rôle autorisé');
assert.match(code,/\{canReceive && <Button/, 'réception réservée au rôle autorisé');
assert.match(code,/\{canMove && <Button/, 'sortie de stock réservée au rôle autorisé');
assert.match(code,/Fournisseurs référencés/,'fournisseurs consultables en fiche');
assert.match(code,/Prix indicatif \/ coût moyen, si autorisé/,'coûts masqués dans liste et disponibles en fiche selon API');
assert.match(code,/Description technique/,'description technique consultable');
assert.match(code,/Proposer une référence/,'création et codification des mousses conservées');
console.log('PASS P5.6/P5.14.4 : TSX syntaxe, 8/4 colonnes,  affichage long, stock, fiche, coût, RBAC, actions, création');
