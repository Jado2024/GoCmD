'use strict'
const fs=require('node:fs')
const path=require('node:path')
const assert=require('node:assert/strict')
const ts=require('typescript')
const root=path.resolve(__dirname,'..')
const read=p=>fs.readFileSync(path.join(root,p),'utf8')
const material=read('src/components/erp/materials-view.tsx')
const da=read('src/components/erp/purchase-dialog.tsx')
for(const [file,code] of [['materials-view.tsx',material],['purchase-dialog.tsx',da]]){
  const ast=ts.createSourceFile(file,code,ts.ScriptTarget.Latest,true,ts.ScriptKind.TSX)
  assert.equal(ast.parseDiagnostics.length,0,file+' : syntaxe TSX')
}
const modal=material.slice(material.indexOf('{/* P5.9 : un seul scroll central'),material.indexOf('      </Dialog>',material.indexOf('{/* P5.9 : un seul scroll central')))
assert.ok(modal.length>10000,'éditeur complet')
assert.match(modal,/h-\[min\(92dvh,860px\)\]/,'hauteur limitée')
assert.match(modal,/sm:max-w-\[920px\]/,'largeur adaptée')
assert.equal((modal.match(/overflow-y-auto/g)||[]).length,1,'un seul scroll vertical')
assert.doesNotMatch(modal,/overflow-x-auto/,'pas de scroll horizontal')
for (const label of ['Famille et unité de stockage','Identité technique de la mousse','Référence et désignation','Paramètres de suivi']) assert.match(modal,new RegExp(label),'section '+label)
assert.ok(modal.indexOf('Famille et unité de stockage')<modal.indexOf('Identité technique de la mousse'))
assert.ok(modal.indexOf('Identité technique de la mousse')<modal.indexOf('Référence et désignation'),'caractéristiques avant code')
assert.ok(modal.indexOf('Référence et désignation')<modal.indexOf('Paramètres de suivi'),'suivi ensuite')
assert.ok(modal.indexOf('min-h-0 flex-1')<modal.indexOf('Actions indépendantes du défilement'),'footer hors scroll')
assert.match(modal,/aria-expanded=\{showTechnicalExtras\}/,'options techniques secondaires repliables')
assert.match(modal,/aria-expanded=\{showStockExtras\}/,'options stock secondaires repliables')
assert.match(modal,/Proposer une référence/,'génération code préservée')
assert.match(modal,/setNameTouched\(false\)/,'régénération nom')
assert.match(modal,/setDescriptionTouched\(false\)/,'régénération description')
for(const field of ['foamNature','foamFormat','foamGrade','foamDensity','foamColor','foamFirmness','foamResilience','foamSupplierGrade','foamLengthCm','foamWidthCm','foamHeightCm','foamThicknessCm']) assert.ok(modal.includes('form.'+field),'champ mousse conservé '+field)
for(const field of ['form.unitPrice','form.minStock','form.location']) assert.ok(modal.includes(field),'paramètre conservé '+field)
assert.match(material,/foamSpecErrors\(foamSpec\)/,'contrôle de spécification')
assert.match(material,/!suggestions.data\?\.duplicate/,'blocage de doublon')
assert.match(material,/method:"POST"/,'création matière conservée')
assert.match(material,/method:"PATCH"/,'modification matière conservée')
assert.match(material,/const canEdit=canCreate/,'RBAC conservé')
assert.match(da,/h-\[min\(92dvh,820px\)\]/,'DA taille adaptée')
assert.equal((da.match(/overflow-y-auto/g)||[]).length,1,'DA scroll unique')
assert.match(da,/aria-label="Effacer la recherche"/,'effacement recherche accessible')
// P5.12 remplace l'étiquette « Ajoutée » par la disparition immédiate à gauche.
assert.match(da,/suggestedMaterials\(/,'P5.12 : les matières ajoutées ne restent plus à gauche')
assert.match(da,/Ajouter/,'action matière explicite')
assert.match(da,/buildPurchaseRequestLines/,'quantités contrôlées')
assert.match(da,/urgentDateMissing = urgent && !expectedDate/,'urgence date requise')
assert.match(da,/supplier: supplier \|\| null/,'fournisseur non imposé')
assert.match(da,/expectedDate: expectedDate \?/,'date facultative')
assert.doesNotMatch(da,/fmtMAD\(|<TableHead[^>]*>PU<\/TableHead>/,'aucun prix acheteur DA')
for(const f of ['src/app/api/materials/route.ts','src/app/api/materials/[id]/route.ts','src/app/api/purchases/route.ts','prisma/schema.prisma']) assert.ok(read(f).length>100,'fichier API/schéma conservé '+f)
console.log('PASS P5.9 : TSX, deux modales fluides, codification, saisie DA, permissions et API conservées (contrôles statiques)')
