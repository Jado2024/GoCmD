const fs=require('fs'); const assert=require('node:assert/strict');
const path=require('node:path'); const Module=require('node:module');
const ts=require('typescript');
const root=path.resolve(__dirname,'..');
const src=fs.readFileSync(path.join(root,'src/lib/sqlite-write.ts'),'utf8');
const js=ts.transpileModule(src,{compilerOptions:{module:ts.ModuleKind.CommonJS,target:ts.ScriptTarget.ES2022}}).outputText;
const mod=new Module(path.join(root,'src/lib/sqlite-write.ts')); mod.filename=path.join(root,'src/lib/sqlite-write.ts'); mod.paths=module.paths;
mod._compile(js,mod.filename);
(async()=>{
 let calls=0;
 const broken=()=>{calls++;return Promise.reject({code:'SQLITE_CORRUPT',message:'database disk image is malformed; database is locked'})};
 await assert.rejects(()=>mod.exports.serializedSQLiteWrite(broken));
 assert.equal(calls,1,'Corruption never retried');
 calls=0;
 await assert.rejects(()=>mod.exports.serializedSQLiteWrite(()=>{calls++;throw {code:'P2010',message:'a permanent error'}}));
 assert.equal(calls,1,'Unexpected error not retried');
 calls=0;
 await mod.exports.serializedSQLiteWrite(async()=>{calls++;if(calls===1)throw{code:'SQLITE_BUSY',message:'database is locked'};return true});
 assert.equal(calls,2,'Safe contention can retry');
 const route=fs.readFileSync(path.join(root,'src/app/api/orders/route.ts'),'utf8');
 const schema=fs.readFileSync(path.join(root,'prisma/schema.prisma'),'utf8');
 assert.match(route,/Idempotency-Key/);
 assert.match(route,/createRequestDigest/);
 assert.match(route,/createRequestKey/);
 assert.match(route,/prior\.createdBy !== actorName/);
 assert.match(schema,/createRequestKey String\? @unique/);
 const form=fs.readFileSync(path.join(root,'src/components/erp/new-order-dialog.tsx'),'utf8');
 assert.match(form,/crypto\.randomUUID\(\)/);
 assert.match(form,/submittedIntent\.current\.payload !== serialized/);
 console.log('PASS P4: SQLITE_CORRUPT fail-closed, contention retry, idempotency contracts');
})().catch(e=>{console.error(e);process.exitCode=1});
