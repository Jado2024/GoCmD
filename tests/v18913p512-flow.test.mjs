import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { commonSupplierIds, suggestedMaterials } from '../src/lib/purchase-suggestions.ts';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const m=(id,stockQty,minStock,supplierIds)=>({id,stockQty,minStock,supplierIds});
const a=m(1,0,100,[1,2]),b=m(2,1,100,[1,3]),c=m(3,0,50,[2,3]),d=m(4,5,10,[1]),e=m(5,500,100,[1,2]);
const all=[a,b,c,d,e];
assert.deepEqual(commonSupplierIds([a]),[1,2]);
assert.deepEqual(commonSupplierIds([a,b]),[1]);
assert.deepEqual(commonSupplierIds([a,b,c]),[]);
assert.deepEqual(suggestedMaterials(all,[], 'all').map(x=>x.id),[1,2,3,4,5]);
assert.deepEqual(suggestedMaterials(all,[a], 'common').map(x=>x.id),[2,3,4]);
assert.deepEqual(suggestedMaterials(all,[a,b], 'common').map(x=>x.id),[4]);
assert.deepEqual(suggestedMaterials(all,[a,b,c], 'common'),[]);
assert.deepEqual(suggestedMaterials(all,[a], 'low').map(x=>x.id),[2,3,4]);
assert.deepEqual(suggestedMaterials(all,[a,b], 'all').map(x=>x.id),[3,4,5]);
assert.deepEqual(suggestedMaterials(all,[a], 'common').find(x=>x.id===a.id),undefined);
assert.deepEqual(suggestedMaterials(all,[], 'common').map(x=>x.id),[1,2,3,4]);
const api=fs.readFileSync(path.join(root,'src/app/api/p2p/consultations/route.ts'),'utf8');
const print=fs.readFileSync(path.join(root,'src/app/api/p2p/consultations/[id]/print/route.ts'),'utf8');
const purchase=fs.readFileSync(path.join(root,'src/components/erp/purchases-view.tsx'),'utf8');
const dialog=fs.readFileSync(path.join(root,'src/components/erp/consultation-dialog.tsx'),'utf8');
assert.ok(api.includes("accessGate(req,'buyer')"));
assert.ok(api.includes("hasPermission(req,'purchases.create')"));
assert.ok(api.includes('AUCUN_FOURNISSEUR_LIGNE'));
assert.ok(api.includes('QTE_SUPERIEURE_RESTE'));
assert.ok(api.includes('tx.supplierRFQ.create'));
assert.ok(api.includes('tx.auditEvent.create'));
assert.ok(print.includes('esc(l.rfq.material.name)'));
assert.ok(fs.readFileSync(path.join(root,'src/app/api/p2p/sourcing/route.ts'),'utf8').includes('FOURNISSEUR_NON_INVITE'));
assert.ok(!print.includes('unitPrice'));
assert.ok(purchase.includes('ConsultationDialog'));
assert.ok(dialog.includes('mailSent:false')===false); // réponse depuis l'API, jamais d'envoi simulé
