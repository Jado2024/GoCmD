import assert from 'node:assert/strict';
import fs from 'node:fs';
import {filterPurchaseCandidates} from '../src/lib/material-da-filters.ts';

const material=(id,name,stockQty,minStock,category='Mousse',suppliers=['Atlas'])=>({id,name,ref:`REF-${id}`,stockQty,minStock,category,supplierNames:suppliers});
const all=[material(1,'Colle',0,15,'Mercerie',['ChimiPlus']),material(2,'Mousse',2,10,'Mousse',['Atlas']),material(3,'Tissu',50,15,'Tissu',['Textiles']),material(4,'Carton',0,0,'Emballage',['Cartons']),material(5,'Feutre',18,20,'Tissu',['Textiles'])];
const presence={1:{historyCount:3,activeCount:1},2:{historyCount:8,activeCount:2},3:{historyCount:1,activeCount:0},5:{historyCount:0,activeCount:0}};
const opt={da:'all',stock:'all',category:'all',supplier:'all',sort:'name'};
const ids=(o)=>filterPurchaseCandidates(all,presence,{...opt,...o}).map(m=>m.id);
assert.deepEqual(ids({da:'active'}),[1,2]);
assert.deepEqual(ids({da:'without'}),[4,5,3]);
assert.deepEqual(ids({da:'history'}),[1,2,3]);
assert.deepEqual(ids({stock:'out'}),[4,1]);
assert.deepEqual(ids({stock:'low'}),[5,2]);
assert.deepEqual(ids({stock:'ok'}),[3]);
assert.deepEqual(ids({da:'without',stock:'out'}),[4]);
assert.deepEqual(ids({da:'active',stock:'low',supplier:'Atlas'}),[2]);
assert.deepEqual(ids({da:'without',stock:'low',category:'Tissu'}),[5]);
assert.deepEqual(ids({sort:'urgency'}),[1,4,2,5,3]);
assert.deepEqual(ids({sort:'stock'}),[4,1,2,5,3]);
assert.equal(all.length,5,'les filtres ne mutent pas la liste source');
const src=file=>fs.readFileSync(new URL(`../${file}`,import.meta.url),'utf8');
const route=src('src/app/api/materials/da-presence/route.ts');
const ui=src('src/components/erp/purchase-dialog.tsx');
const post=src('src/app/api/purchases/route.ts');
assert.match(route,/readRoleGate\(req, \["buyer", "approver"\]\)/,'les droits sont contrôlés');
assert.equal((route.match(/purchaseRequestLine\.groupBy/g)||[]).length,2,'groupements exhaustifs sans limite de pagination');
assert.match(route,/Cache-Control.*no-store/,'éviter cache partagé');
assert.match(route,/"partially_approved", "ordered", "partial"/,'statuts alignés au garde serveur');
assert.match(post,/'partially_approved','ordered','partial'/,'garde anti-doublon serveur conservé');
assert.match(ui,/daPresence\.isSuccess \? filterPurchaseCandidates/,'pas de déclaration sans DA lorsque la situation est inconnue');
assert.match(ui,/requiresJustification[\s\S]*?daPresence\.data\?\.byMaterial/,'avec DA actif impose une justification');
assert.match(ui,/daPresence\.isSuccess && !daPresence\.isFetching/,'bloque la soumission si état DA indisponible');
assert.match(ui,/Filtrer par DA existante/);
assert.match(ui,/Filtrer par stock/);
assert.match(ui,/Filtrer par famille/);
assert.match(ui,/Filtrer par fournisseur/);
console.log('PASS P5.15.16 : 13 scénarios de filtrage et contrôles source RBAC/DA non paginée/anti-doublon');
