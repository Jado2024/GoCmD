assert.match(create,/serializedSQLiteWrite/)
assert.match(create,/MATERIAL_CREATED/)
assert.match(create,/stockQty:0/)
assert.match(create,/DUPLICATE_REF/)
assert.match(create,/foamNature==="AGGLO"&&parsed\.data\.foamFormat==="ROULEAU"/)
assert.match(update,/UNIT_HAS_HISTORY/)
assert.match(update,/MATERIAL_UPDATED/)
assert.match(get,/accessGate\(req, "buyer"\)/)
assert.match(get,/nextFoamReference/)
