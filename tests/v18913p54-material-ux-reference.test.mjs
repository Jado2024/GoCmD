import assert from 'node:assert/strict'
import fs from 'node:fs'
import {foamReferencePrefix, nextFoamReference, MATERIAL_CATEGORIES, MATERIAL_UNITS} from '../src/lib/material-reference.ts'

const prefix = foamReferencePrefix('PURE','BLOC',30)
assert.equal(prefix,'MP-MOU-PUR-BLC-D30')
assert.equal(foamReferencePrefix('AGGLO','BLOC',60),'MP-MOU-AGG-BLC-D60')
assert.equal(foamReferencePrefix('PURE','PLAQUE',25),'MP-MOU-PUR-PLQ-D25')
assert.equal(foamReferencePrefix('PURE','ROULEAU',30.5),'MP-MOU-PUR-ROL-D30P5')
assert.equal(foamReferencePrefix('AGGLO','ROULEAU',30),null,'Rouleau aggloméré interdit')
for(const invalid of [-1,0,501,Number.NaN,Number.POSITIVE_INFINITY])assert.equal(foamReferencePrefix('PURE','BLOC',invalid),null)
assert.equal(foamReferencePrefix('NO','BLOC',30),null)
assert.equal(foamReferencePrefix('PURE','FAUX',30),null)
assert.equal(nextFoamReference(prefix,[]),'MP-MOU-PUR-BLC-D30-001')
assert.equal(nextFoamReference(prefix,['MP-MOU-PUR-BLC-D30-001','MP-MOU-PUR-BLC-D30-002']),'MP-MOU-PUR-BLC-D30-003')
assert.equal(nextFoamReference(prefix,['MP-MOU-PUR-BLC-D30-001','MP-MOU-PUR-BLC-D30-003']),'MP-MOU-PUR-BLC-D30-002')
assert.equal(nextFoamReference(prefix,['mp-mou-pur-blc-d30-001']),'MP-MOU-PUR-BLC-D30-002','insensibilité à la casse')
assert.equal(nextFoamReference(prefix,['MP-MOU-PUR-BLC-D30-XYZ','MP-MOU-PUR-BLC-D300-001']),'MP-MOU-PUR-BLC-D30-001')
assert.ok(MATERIAL_CATEGORIES.includes('Mousse'))
assert.ok(MATERIAL_CATEGORIES.includes('Tissu'),'préserver les libellés de la base démo')
assert.ok(MATERIAL_CATEGORIES.includes('Emballage & consommables'))
for(const unit of ['kg','m³','ml','pcs'])assert.ok(MATERIAL_UNITS.includes(unit))
const src = name=>fs.readFileSync(name,'utf8')
